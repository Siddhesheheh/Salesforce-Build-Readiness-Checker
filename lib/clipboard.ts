import { ReadinessReport } from "./types";

export function formatClarifyingQuestions(report: ReadinessReport, requirementTitle?: string): string {
  const lines: string[] = [];
  lines.push("=======================================================");
  lines.push("SALESFORCE BUILD READINESS — CLARIFYING QUESTIONS");
  lines.push("=======================================================");
  if (requirementTitle) {
    lines.push(`Requirement: ${requirementTitle}`);
  }
  lines.push(`Readiness Verdict: ${report.readiness_verdict}`);
  lines.push(`Summary: ${report.summary}`);
  lines.push(`Findings: ${report.counts.blockers} Blocker(s), ${report.counts.important} Important, ${report.counts.minor} Minor`);
  lines.push("-------------------------------------------------------");
  lines.push("ACTION ITEMS & QUESTIONS FOR PM / BA FOLLOW-UP:");
  lines.push("-------------------------------------------------------");

  const findingsWithQuestions = report.findings.filter(
    (f) => f.question_for_pm && f.question_for_pm.trim().length > 0
  );

  if (findingsWithQuestions.length === 0) {
    lines.push("No clarifying questions needed. Requirement satisfies all readiness criteria.");
  } else {
    findingsWithQuestions.forEach((finding, index) => {
      lines.push(
        `\n${index + 1}. [${finding.severity.toUpperCase()}] ${finding.title} (${finding.category})`
      );
      lines.push(`   Question for PM: ${finding.question_for_pm}`);
      lines.push(`   What's Missing:  ${finding.whats_missing}`);
      lines.push(`   Why It Matters:  ${finding.why_it_matters}`);
      if (finding.verify_in_org && finding.verify_in_org.trim().length > 0) {
        lines.push(`   Verify in Org:   ${finding.verify_in_org}`);
      }
    });
  }

  lines.push("\n=======================================================");
  lines.push("Generated by Salesforce Build Readiness Checker");
  lines.push("=======================================================");

  return lines.join("\n");
}

export async function copyToClipboard(text: string): Promise<boolean> {
  if (typeof navigator !== "undefined" && navigator.clipboard && navigator.clipboard.writeText) {
    try {
      await navigator.clipboard.writeText(text);
      return true;
    } catch {
      // Fallback
    }
  }

  // Fallback for environments where navigator.clipboard might fail
  if (typeof document !== "undefined") {
    try {
      const textarea = document.createElement("textarea");
      textarea.value = text;
      textarea.style.position = "fixed";
      textarea.style.opacity = "0";
      document.body.appendChild(textarea);
      textarea.select();
      const successful = document.execCommand("copy");
      document.body.removeChild(textarea);
      return successful;
    } catch {
      return false;
    }
  }

  return false;
}
